"""Compile mathematical expression strings into callable PyTorch update rules.

This module takes free-form math expressions (generated by an LLM or hand-written)
and compiles them into step functions compatible with the Lenia simulation loop.

The compiled function signature is:  step_fn(state_tensor) -> new_state_tensor

Safety:
  - Uses a restricted eval namespace (no builtins, no file I/O)
  - Per-step timeout via signal (Unix only)
  - All exceptions caught and re-raised as CompilationError or RuntimeError
"""

from __future__ import annotations

import math
import signal
from typing import Callable, Optional

import torch
import torch.nn.functional as F


# ---------------------------------------------------------------------------
# Exceptions
# ---------------------------------------------------------------------------

class CompilationError(Exception):
    """Raised when an expression string cannot be compiled."""
    pass


class StepTimeoutError(Exception):
    """Raised when a single simulation step exceeds the time limit."""
    pass


# ---------------------------------------------------------------------------
# Helper operations available inside expressions
# ---------------------------------------------------------------------------

def _build_gaussian_kernel(resolution: int, radius: int = 13) -> torch.Tensor:
    """Build a normalised Gaussian convolution kernel, FFT-ready.

    Returns the FFT2 of the kernel (complex tensor of shape [resolution, resolution]).
    """
    R = resolution
    mid = R // 2
    y = torch.arange(R, dtype=torch.float32) - mid
    x = torch.arange(R, dtype=torch.float32) - mid
    yy, xx = torch.meshgrid(y, x, indexing="ij")
    dist = torch.sqrt(xx ** 2 + yy ** 2) / max(radius, 1.0)

    # Gaussian profile with compact support
    raw = torch.exp(-((dist * 1.0 - 1.0).pow(2)) / (2 * 0.15 ** 2))
    raw = raw * (dist <= 1.0).float()

    # Normalise
    total = raw.sum()
    if total > 0:
        raw = raw / total

    # Shift for FFT convolution (centre at 0,0)
    kernel_shifted = torch.roll(raw, shifts=(-mid, -mid), dims=(0, 1))
    return torch.fft.fft2(kernel_shifted)


def _make_conv_fn(kernel_fft: torch.Tensor):
    """Return a function that convolves a 2D state with the pre-computed kernel."""

    def conv(A: torch.Tensor) -> torch.Tensor:
        state_fft = torch.fft.fft2(A)
        return torch.fft.ifft2(state_fft * kernel_fft).real

    return conv


def _laplacian(A: torch.Tensor) -> torch.Tensor:
    """Discrete Laplacian using a 3x3 stencil with periodic boundary."""
    Ap = A.unsqueeze(0).unsqueeze(0)  # [1, 1, H, W]
    Ap = F.pad(Ap, (1, 1, 1, 1), mode="circular")
    kernel = torch.tensor(
        [[0.0, 1.0, 0.0], [1.0, -4.0, 1.0], [0.0, 1.0, 0.0]],
        dtype=A.dtype, device=A.device,
    ).unsqueeze(0).unsqueeze(0)
    result = F.conv2d(Ap, kernel)
    return result.squeeze(0).squeeze(0)


def _gradient_x(A: torch.Tensor) -> torch.Tensor:
    """Horizontal gradient (central difference) with periodic boundary."""
    return (torch.roll(A, -1, dims=1) - torch.roll(A, 1, dims=1)) / 2.0


def _gradient_y(A: torch.Tensor) -> torch.Tensor:
    """Vertical gradient (central difference) with periodic boundary."""
    return (torch.roll(A, -1, dims=0) - torch.roll(A, 1, dims=0)) / 2.0


def _clip(x, lo=0.0, hi=1.0):
    """Clip tensor values to [lo, hi]."""
    if isinstance(x, torch.Tensor):
        return x.clamp(min=float(lo), max=float(hi))
    return max(lo, min(hi, x))


def _threshold(x: torch.Tensor, t: float = 0.5) -> torch.Tensor:
    """Hard threshold: returns 1 where x > t, else 0."""
    return (x > t).float()


def _safe_sqrt(x):
    """Square root with clamped input to avoid NaN."""
    if isinstance(x, torch.Tensor):
        return torch.sqrt(x.clamp(min=0.0))
    return math.sqrt(max(0.0, x))


def _safe_log(x):
    """Logarithm with clamped input to avoid -inf/NaN."""
    if isinstance(x, torch.Tensor):
        return torch.log(x.clamp(min=1e-10))
    return math.log(max(x, 1e-10))


def _safe_div(a, b):
    """Division with small epsilon to avoid division by zero."""
    if isinstance(b, torch.Tensor):
        return a / (b + 1e-10)
    if isinstance(a, torch.Tensor):
        return a / (b + 1e-10)
    return a / (b + 1e-10)


def _torch_max(a, b):
    """Element-wise maximum that handles mixed tensor/scalar."""
    if isinstance(a, torch.Tensor) and isinstance(b, torch.Tensor):
        return torch.maximum(a, b)
    if isinstance(a, torch.Tensor):
        return torch.clamp(a, min=float(b))
    if isinstance(b, torch.Tensor):
        return torch.clamp(b, min=float(a))
    return max(a, b)


def _torch_min(a, b):
    """Element-wise minimum that handles mixed tensor/scalar."""
    if isinstance(a, torch.Tensor) and isinstance(b, torch.Tensor):
        return torch.minimum(a, b)
    if isinstance(a, torch.Tensor):
        return torch.clamp(a, max=float(b))
    if isinstance(b, torch.Tensor):
        return torch.clamp(b, max=float(a))
    return min(a, b)


