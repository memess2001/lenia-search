def _conserve(A: torch.Tensor, B: torch.Tensor, target: float = 1.0) -> tuple:
    """Normalize A and B so that A + B = target locally. Returns (A_new, B_new)."""
    total = A + B + 1e-10
    scale = target / total
    return (A * scale).clamp(0, 1), (B * scale).clamp(0, 1)


def _conserve_a(A: torch.Tensor, B: torch.Tensor, target: float = 1.0) -> torch.Tensor:
    """Return conserved A field (A + B normalized to target)."""
    total = A + B + 1e-10
    return (A * target / total).clamp(0, 1)


def _conserve_b(A: torch.Tensor, B: torch.Tensor, target: float = 1.0) -> torch.Tensor:
    """Return conserved B field."""
    total = A + B + 1e-10
    return (B * target / total).clamp(0, 1)


def _rotate_cw(F: torch.Tensor) -> torch.Tensor:
    """Clockwise rotation by 90 degrees — chiral operation."""
    gx = (torch.roll(F, -1, dims=1) - torch.roll(F, 1, dims=1)) / 2.0
    gy = (torch.roll(F, -1, dims=0) - torch.roll(F, 1, dims=0)) / 2.0
    return torch.sqrt(gx**2 + gy**2 + 1e-10)


def _rotate_ccw(F: torch.Tensor) -> torch.Tensor:
    """Counter-clockwise rotation — opposite chirality."""
    gx = (torch.roll(F, 1, dims=1) - torch.roll(F, -1, dims=1)) / 2.0
    gy = (torch.roll(F, 1, dims=0) - torch.roll(F, -1, dims=0)) / 2.0
    return torch.sqrt(gx**2 + gy**2 + 1e-10)


def _curl(F: torch.Tensor) -> torch.Tensor:
    """Curl (vorticity) of a scalar field — detects rotational structure."""
    gx = (torch.roll(F, -1, dims=1) - torch.roll(F, 1, dims=1)) / 2.0
    gy = (torch.roll(F, -1, dims=0) - torch.roll(F, 1, dims=0)) / 2.0
    # curl = d(gy)/dx - d(gx)/dy
    dgydx = (torch.roll(gy, -1, dims=1) - torch.roll(gy, 1, dims=1)) / 2.0
    dgxdy = (torch.roll(gx, -1, dims=0) - torch.roll(gx, 1, dims=0)) / 2.0
    return dgydx - dgxdy


def _global_mean(F: torch.Tensor) -> torch.Tensor:
    """Global mean — for conservation-type expressions."""
    return torch.full_like(F, F.mean().item())


def _compete(A: torch.Tensor, B: torch.Tensor, strength: float = 1.0) -> torch.Tensor:
    """Competition term: A's growth is suppressed where B is strong."""
    return A * (1.0 - strength * B).clamp(min=0.0)


